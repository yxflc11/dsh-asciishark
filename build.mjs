import { build } from "esbuild";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";

// 1. Bundle the ocean worker separately and inline it into the client bundle,
//    so the worker can be started from a Blob URL without extra requests.
await mkdir(".tmp", { recursive: true });
await build({
  entryPoints: ["src/ocean-worker.ts"],
  bundle: true,
  format: "iife",
  target: ["chrome110"],
  outfile: ".tmp/ocean-worker.js",
  legalComments: "none",
  logLevel: "info",
});
const workerSource = await readFile(".tmp/ocean-worker.js", "utf8");
await writeFile(
  "src/worker-source.generated.ts",
  "/** Generated by build: the bundled ocean worker source, inlined for a Blob URL. */\n" +
    "export const WORKER_SOURCE = " +
    JSON.stringify(workerSource) +
    ";\n",
);

// 2. Browser half: lazy-CJS bundle registering the plugin factory.
await build({
  entryPoints: ["src/client.ts"],
  bundle: true,
  format: "iife",
  target: ["chrome110"],
  outfile: "lib/client.js",
  legalComments: "none",
  logLevel: "info",
});

// 3. Standalone preview: exposes `window.OceanEngine` for preview/index.html.
await build({
  entryPoints: ["src/preview.ts"],
  bundle: true,
  format: "iife",
  target: ["chrome110"],
  outfile: "preview/ocean.global.js",
  legalComments: "none",
  logLevel: "info",
});

await rm(".tmp", { recursive: true, force: true });
